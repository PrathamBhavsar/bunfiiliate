//! Tenant audit inventory: every route (OpenAPI + tracker) needs an annotation, and
//! `docs/audit/tenant-inventory.md` is generated from them. `UPDATE_INVENTORY=1` rewrites it.

use std::collections::BTreeSet;
use std::path::PathBuf;

const KINDS: [&str; 6] = ["scoped", "public", "self", "super", "apikey", "webhook"];

type Route = (String, String, Vec<String>, &'static str);

#[derive(Debug, Clone, Default)]
struct Ann {
    method: String,
    path: String,
    source: String,
    kind: String,
    role: String,
    reason: String,
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn parse_annotations(text: &str) -> Vec<Ann> {
    let mut out: Vec<Ann> = Vec::new();
    let mut cur: Option<Ann> = None;
    for line in text.lines().map(str::trim) {
        if line == "[[route]]" {
            out.extend(cur.take());
            cur = Some(Ann::default());
        } else if let (Some(a), Some((k, v))) = (cur.as_mut(), line.split_once(" = ")) {
            let v = v.trim().trim_matches('"').to_owned();
            match k {
                "method" => a.method = v,
                "path" => a.path = v,
                "source" => a.source = v,
                "kind" => a.kind = v,
                "role" => a.role = v,
                "reason" => a.reason = v,
                other => panic!("unknown annotation key {other}"),
            }
        }
    }
    out.extend(cur);
    out
}

fn annotations() -> Vec<Ann> {
    let text = std::fs::read_to_string(root().join("docs/audit/tenant-annotations.toml")).unwrap();
    parse_annotations(&text)
}

fn routes() -> Vec<Route> {
    let mut out: Vec<Route> = api::routes::route_table()
        .into_iter()
        .map(|r| (r.method, r.path, r.path_params, "api"))
        .collect();
    out.push(("get".into(), "/api/openapi.json".into(), vec![], "api"));
    out.extend(tracker_routes());
    out.sort();
    out
}

/// The tracker is a separate binary, so read its router source: `.route("/p", get(..).post(..))`.
fn tracker_routes() -> Vec<Route> {
    let src = std::fs::read_to_string(root().join("crates/tracker/src/lib.rs")).unwrap();
    let start = src.find("pub fn router").expect("tracker router fn");
    let body = &src[start..];
    let body = &body[..body.find("\nasync fn ").unwrap_or(body.len())];
    let mut out = Vec::new();
    for chunk in body.split(".route(").skip(1) {
        let chunk = chunk.trim_start();
        let path = chunk[1..].split('"').next().unwrap().to_owned();
        let rest = &chunk[path.len() + 2..];
        let rest = rest.split(".layer(").next().unwrap();
        let params: Vec<String> = path
            .split('/')
            .filter_map(|s| s.strip_prefix('{')?.strip_suffix('}'))
            .map(str::to_owned)
            .collect();
        for m in ["get", "post", "put", "patch", "delete"] {
            let needle = format!("{m}(");
            let hit = rest
                .match_indices(&needle)
                .any(|(i, _)| i == 0 || !rest.as_bytes()[i - 1].is_ascii_alphanumeric());
            if hit {
                out.push((m.to_owned(), path.clone(), params.clone(), "tracker"));
            }
        }
    }
    out
}

fn render(anns: &[Ann]) -> String {
    let mut rows = routes();
    rows.sort_by(|a, b| (a.3, &a.1, &a.0).cmp(&(b.3, &b.1, &b.0)));
    let mut s = String::from(
        "# Tenant route inventory\n\nGenerated by `cargo test -p api --test tenant_inventory` \
         (`UPDATE_INVENTORY=1` rewrites). Edit `tenant-annotations.toml`, not this file.\n\n\
         | method | path | source | auth role | id params | kind | reason |\n\
         |---|---|---|---|---|---|---|\n",
    );
    for (m, p, params, src) in rows {
        let a = anns
            .iter()
            .find(|a| a.method == m && a.path == p && a.source == src);
        let (role, kind, reason) = a.map_or(("?", "?", "?"), |a| {
            (a.role.as_str(), a.kind.as_str(), a.reason.as_str())
        });
        s.push_str(&format!(
            "| {} | `{p}` | {src} | {role} | {} | {kind} | {reason} |\n",
            m.to_uppercase(),
            params.join(", ")
        ));
    }
    s
}

#[test]
fn inventory_matches_doc() {
    let want = render(&annotations());
    let path = root().join("docs/audit/tenant-inventory.md");
    if std::env::var_os("UPDATE_INVENTORY").is_some() {
        std::fs::write(&path, &want).unwrap();
    }
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    assert_eq!(
        have, want,
        "docs/audit/tenant-inventory.md is stale: run UPDATE_INVENTORY=1 cargo test -p api --test tenant_inventory"
    );
}

#[test]
fn every_route_is_annotated() {
    let anns = annotations();
    let missing: Vec<_> = routes()
        .into_iter()
        .filter(|(m, p, _, s)| {
            !anns
                .iter()
                .any(|a| &a.method == m && &a.path == p && a.source == *s)
        })
        .map(|(m, p, _, s)| format!("{s} {m} {p}"))
        .collect();
    assert!(missing.is_empty(), "unannotated routes: {missing:#?}");
}

#[test]
fn annotations_have_no_orphans() {
    let have: BTreeSet<_> = routes()
        .into_iter()
        .map(|(m, p, _, s)| (m, p, s.to_owned()))
        .collect();
    let orphans: Vec<_> = annotations()
        .into_iter()
        .filter(|a| !have.contains(&(a.method.clone(), a.path.clone(), a.source.clone())))
        .map(|a| format!("{} {} {}", a.source, a.method, a.path))
        .collect();
    assert!(
        orphans.is_empty(),
        "annotations without a route: {orphans:#?}"
    );
}

#[test]
fn annotations_are_well_formed_and_unique() {
    let mut seen = BTreeSet::new();
    for a in annotations() {
        assert!(KINDS.contains(&a.kind.as_str()), "bad kind: {a:?}");
        assert!(!a.reason.is_empty(), "reason required: {a:?}");
        assert!(["api", "tracker"].contains(&a.source.as_str()), "{a:?}");
        assert!(
            seen.insert((a.method.clone(), a.path.clone(), a.source.clone())),
            "duplicate annotation: {a:?}"
        );
    }
}

#[test]
fn api_kinds_match_declared_security() {
    let secured: BTreeSet<_> = api::routes::route_table()
        .into_iter()
        .filter(|r| r.secured)
        .map(|r| (r.method, r.path))
        .collect();
    for a in annotations().iter().filter(|a| a.source == "api") {
        let is_secured = secured.contains(&(a.method.clone(), a.path.clone()));
        match a.kind.as_str() {
            "public" => assert!(!is_secured, "public route declares security: {a:?}"),
            "scoped" | "super" | "self" => {
                assert!(is_secured, "{} route lacks security: {a:?}", a.kind)
            }
            k => panic!("kind {k} not valid for an api route: {a:?}"),
        }
        match a.kind.as_str() {
            "scoped" => assert_eq!(a.role, "Admin", "{a:?}"),
            "super" => assert_eq!(a.role, "SuperAdmin", "{a:?}"),
            "public" => assert_eq!(a.role, "none", "{a:?}"),
            _ => {}
        }
    }
}

#[test]
fn tracker_key_routes_are_apikey_or_webhook() {
    let anns = annotations();
    let tracker: Vec<_> = routes().into_iter().filter(|r| r.3 == "tracker").collect();
    assert!(tracker.len() >= 8, "tracker routes not parsed: {tracker:?}");
    for (m, p, params, s) in tracker {
        let a = anns
            .iter()
            .find(|a| a.method == m && a.path == p && a.source == s)
            .unwrap();
        if params.iter().any(|x| x == "key") {
            let want = if p.contains("/webhooks/") {
                "webhook"
            } else {
                "apikey"
            };
            assert_eq!(a.kind, want, "{p}");
        } else {
            assert_eq!(a.kind, "public", "{p}");
        }
    }
}

#[test]
fn public_routes_allowlist() {
    let got: BTreeSet<String> = annotations()
        .into_iter()
        .filter(|a| a.kind == "public")
        .map(|a| format!("{} {} {}", a.source, a.method, a.path))
        .collect();
    let want: BTreeSet<String> = [
        "api get /api/openapi.json",
        "api get /healthz",
        "api get /readyz",
        "api post /api/v1/affiliates/register",
        "api post /api/v1/auth/login",
        "api post /api/v1/auth/refresh",
        "api post /api/v1/auth/logout",
        "api get /api/v1/auth/csrf",
        "api post /api/v1/auth/password/reset",
        "api post /api/v1/auth/password/reset-with-token",
        "api post /api/v1/contact-requests",
        "api post /api/v1/webhooks/billing/{provider}",
        "tracker get /t.js",
        "tracker get /r/{code}",
        "tracker post /c",
        "tracker post /v2/c",
        "tracker get /v2/openapi.json",
        "tracker get /healthz",
        "tracker get /v2/openapi.json",
        "tracker get /readyz",
    ]
    .map(str::to_owned)
    .into();
    assert_eq!(
        got, want,
        "public route set changed: decide and update this list"
    );
}
